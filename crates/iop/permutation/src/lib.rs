//! The permutation argument: copy constraints between the cells of chosen
//! columns, by a grand product over cosets.
//!
//! # The relation
//!
//! Take `k` columns of `n` values, `w_0, ..., w_(k-1)`, the cell `(c, i)`
//! having index `c n + i`. A [`Permutation`] `sigma` of the `k n` cells
//! is respected when every cell holds the value of its image:
//! `w(sigma(x)) = w(x)`. The copies of a circuit generate an equivalence
//! relation on the cells; `sigma` cycles through each class
//! ([`Permutation::from_copies`]), so it is respected exactly when the
//! columns are constant on the classes. (Our framing: the cyclic group
//! generated by `sigma` acts on the cells with the classes as orbits, and a
//! respected assignment is a function on the orbit space.)
//!
//! # The argument
//!
//! Gabizon, Williamson and Ciobotaru, *PlonK*, ePrint 2019/953.
//! Label the cell `(c, i)` with `k_c w^i`, for `w` the generator of the
//! domain `H` of order `n` and shifts `k_c` in distinct cosets of `H`
//! ([`shifts`]), so the labels of distinct cells differ. With challenges
//! `beta, gamma`, the columns respect `sigma` iff, except with probability
//! about `k n / |F|`,
//!
//! ```text
//! prod_(c, i) (w_c(i) + beta k_c w^i + gamma) = prod_(c, i) (w_c(i) + beta label(sigma(c, i)) + gamma),
//! ```
//!
//! which the grand product `z` ([`grand_product`]) checks row by row:
//! `z(w^0) = 1` and `z(w^(i+1)) = z(w^i) num_i / den_i`. As identities on
//! `H` ([`terms`]):
//!
//! ```text
//! z(X) prod_c (w_c(X) + beta k_c X + gamma) - z(w X) prod_c (w_c(X) + beta sigma_c(X) + gamma) = 0,
//! L_0(X) (z(X) - 1) = 0,
//! ```
//!
//! where `sigma_c` interpolates the labels of the images of column `c`'s
//! cells ([`labels`]). The first identity has degree `k + 1` in the column
//! polynomials.
//!
//! The protocols of `arrabbiata-plonk` and `arrabbiata-generalized-plonk`
//! both use this crate, so the argument is written once.
//!
//! ```
//! use arrabbiata_field::{Field, TwoAdicField};
//! use arrabbiata_pasta::Fq as F;
//! use arrabbiata_permutation::{Permutation, grand_product, labels, shifts};
//! use arrabbiata_poly::Domain;
//!
//! // Two columns of four rows; copy (0, 1) to (1, 2).
//! let columns = 2;
//! let rows = 4;
//! let copies = [(1, 4 + 2)];
//! let sigma = Permutation::from_copies(columns, rows, &copies).unwrap();
//! let domain = Domain::<F>::new(2).unwrap();
//! let k = shifts::<F>(columns, rows).unwrap();
//! let sigma_labels = labels(&sigma, &k, &domain);
//! let beta = F::from_u64(3);
//! let gamma = F::from_u64(5);
//! let good = [vec![F::ONE, F::from_u64(7), F::ZERO, F::ZERO], vec![F::ZERO, F::ZERO, F::from_u64(7), F::ZERO]];
//! let z = grand_product(&good, &k, &sigma_labels, &domain, beta, gamma).unwrap();
//! assert_eq!(z[0], F::ONE);
//! assert!(sigma.is_respected_by(&good));
//! // The product closes: the last step returns to 1 exactly when respected.
//! assert!(arrabbiata_permutation::closes(&good, &k, &sigma_labels, &domain, &z, beta, gamma));
//! let mut bad = good.clone();
//! bad[1][2] = F::from_u64(8);
//! let z = grand_product(&bad, &k, &sigma_labels, &domain, beta, gamma).unwrap();
//! assert!(!sigma.is_respected_by(&bad));
//! assert!(!arrabbiata_permutation::closes(&bad, &k, &sigma_labels, &domain, &z, beta, gamma));
//! ```

#![no_std]

extern crate alloc;

use alloc::{vec, vec::Vec};
use core::fmt;

use arrabbiata_field::{Field, TwoAdicField};
use arrabbiata_poly::Domain;

/// Why building or running the argument failed.
///
/// ```
/// use arrabbiata_permutation::Error;
/// assert_eq!(Error::Shape.to_string(), "not a permutation of the cells, or the wrong shape");
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Error {
    /// Not a permutation of the cells, or columns of the wrong shape.
    Shape,
    /// The field has no `k` shifts in distinct cosets of the domain.
    CosetShifts,
    /// A denominator of the grand product vanished (probability about
    /// `k n / |F|` over `gamma` for respected columns).
    Denominator,
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Shape => write!(f, "not a permutation of the cells, or the wrong shape"),
            Self::CosetShifts => write!(f, "the field has no distinct cosets for the shifts"),
            Self::Denominator => write!(f, "a denominator of the grand product vanished"),
        }
    }
}

impl core::error::Error for Error {}

/// A permutation `sigma` of the `k n` cells of `k` columns of `n` rows, the
/// cell `(c, i)` having index `c n + i`.
///
/// ```
/// use arrabbiata_permutation::{Error, Permutation};
/// let p = Permutation::new(1, 2, vec![1, 0]).unwrap();
/// assert_eq!(p.sigma(), &[1, 0]);
/// assert_eq!(Permutation::new(1, 2, vec![0, 0]).unwrap_err(), Error::Shape);
/// ```
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Permutation {
    columns: usize,
    rows: usize,
    sigma: Vec<usize>,
}

impl Permutation {
    /// The permutation `sigma` of the cells of `columns` columns of `rows`
    /// rows.
    ///
    /// # Errors
    ///
    /// [`Error::Shape`] if `sigma` is not a permutation of `0..columns * rows`.
    ///
    /// ```
    /// use arrabbiata_permutation::Permutation;
    /// assert!(Permutation::new(2, 2, vec![3, 1, 2, 0]).is_ok());
    /// ```
    pub fn new(columns: usize, rows: usize, sigma: Vec<usize>) -> Result<Self, Error> {
        let cells = columns * rows;
        if sigma.len() != cells {
            return Err(Error::Shape);
        }
        let mut seen = vec![false; cells];
        for target in &sigma {
            if *target >= cells || seen[*target] {
                return Err(Error::Shape);
            }
            seen[*target] = true;
        }
        Ok(Self {
            columns,
            rows,
            sigma,
        })
    }

    /// The identity: no copy.
    ///
    /// ```
    /// use arrabbiata_permutation::Permutation;
    /// assert_eq!(Permutation::identity(2, 2).sigma(), &[0, 1, 2, 3]);
    /// ```
    #[must_use]
    pub fn identity(columns: usize, rows: usize) -> Self {
        Self {
            columns,
            rows,
            sigma: (0..columns * rows).collect(),
        }
    }

    /// The permutation cycling through each class of the equivalence
    /// relation the `copies` generate (pairs of cell indices), each class
    /// in increasing order: so it depends on the classes only, not on the
    /// order or the redundancy of the copies.
    ///
    /// # Errors
    ///
    /// [`Error::Shape`] if a copy names a cell out of range.
    ///
    /// ```
    /// use arrabbiata_permutation::Permutation;
    /// // 0 ~ 2 ~ 3, and 1 alone: the cycle 0 -> 2 -> 3 -> 0.
    /// let p = Permutation::from_copies(1, 4, &[(3, 0), (2, 3)]).unwrap();
    /// assert_eq!(p.sigma(), &[2, 1, 3, 0]);
    /// assert_eq!(p, Permutation::from_copies(1, 4, &[(0, 2), (2, 3), (0, 3)]).unwrap());
    /// ```
    pub fn from_copies(
        columns: usize,
        rows: usize,
        copies: &[(usize, usize)],
    ) -> Result<Self, Error> {
        let size = columns * rows;
        if copies.iter().any(|(x, y)| *x >= size || *y >= size) {
            return Err(Error::Shape);
        }
        let mut parent: Vec<usize> = (0..size).collect();
        fn find(parent: &mut [usize], mut x: usize) -> usize {
            while parent[x] != x {
                parent[x] = parent[parent[x]];
                x = parent[x];
            }
            x
        }
        for (x, y) in copies {
            let rx = find(&mut parent, *x);
            let ry = find(&mut parent, *y);
            if rx != ry {
                parent[rx] = ry;
            }
        }
        let mut members: Vec<Vec<usize>> = vec![Vec::new(); size];
        for cell in 0..size {
            let root = find(&mut parent, cell);
            members[root].push(cell);
        }
        let mut sigma: Vec<usize> = (0..size).collect();
        for class in &members {
            for (i, cell) in class.iter().enumerate() {
                sigma[*cell] = class[(i + 1) % class.len()];
            }
        }
        Ok(Self {
            columns,
            rows,
            sigma,
        })
    }

    /// The image of each cell.
    ///
    /// ```
    /// use arrabbiata_permutation::Permutation;
    /// assert_eq!(Permutation::identity(1, 2).sigma(), &[0, 1]);
    /// ```
    #[must_use]
    pub fn sigma(&self) -> &[usize] {
        &self.sigma
    }

    /// The number of columns.
    ///
    /// ```
    /// use arrabbiata_permutation::Permutation;
    /// assert_eq!(Permutation::identity(3, 2).columns(), 3);
    /// ```
    #[must_use]
    pub const fn columns(&self) -> usize {
        self.columns
    }

    /// The number of rows.
    ///
    /// ```
    /// use arrabbiata_permutation::Permutation;
    /// assert_eq!(Permutation::identity(3, 2).rows(), 2);
    /// ```
    #[must_use]
    pub const fn rows(&self) -> usize {
        self.rows
    }

    /// Whether `columns` (one slice per permuted column, `rows` values each)
    /// hold the value of each cell's image in the cell.
    ///
    /// ```
    /// use arrabbiata_permutation::Permutation;
    /// let p = Permutation::new(1, 2, vec![1, 0]).unwrap();
    /// assert!(p.is_respected_by(&[vec![5, 5]]));
    /// assert!(!p.is_respected_by(&[vec![5, 6]]));
    /// ```
    #[must_use]
    pub fn is_respected_by<T, C>(&self, columns: &[C]) -> bool
    where
        T: PartialEq,
        C: AsRef<[T]>,
    {
        let n = self.rows;
        if columns.len() != self.columns || columns.iter().any(|c| c.as_ref().len() != n) {
            return false;
        }
        self.sigma.iter().enumerate().all(|(cell, target)| {
            columns[cell / n].as_ref()[cell % n] == columns[target / n].as_ref()[target % n]
        })
    }
}

/// The shifts `g^c`, `c < k`, of the cosets `g^c H` labelling `k` columns
/// of `n` rows, `g` the multiplicative generator. `g^i H` and `g^j H` are
/// disjoint iff `g^((i - j) n) != 1`, so it suffices that `g^(m n) != 1`
/// for `0 < m < k`.
///
/// # Errors
///
/// [`Error::CosetShifts`] if two shifts fall in the same coset.
///
/// ```
/// use arrabbiata_field::{Field, TwoAdicField};
/// use arrabbiata_pasta::Fq as F;
/// use arrabbiata_permutation::shifts;
/// let k = shifts::<F>(3, 8).unwrap();
/// assert_eq!(k[0], F::ONE);
/// assert_eq!(k[2], F::MULTIPLICATIVE_GENERATOR.pow(2));
/// ```
pub fn shifts<F>(columns: usize, rows: usize) -> Result<Vec<F>, Error>
where
    F: TwoAdicField,
{
    let g = F::MULTIPLICATIVE_GENERATOR;
    let gn = g.pow(rows as u64);
    let mut power = F::ONE;
    for _ in 1..columns {
        power = power * gn;
        if power == F::ONE {
            return Err(Error::CosetShifts);
        }
    }
    Ok((0..columns).map(|c| g.pow(c as u64)).collect())
}

/// The labels of the images: for each column `c` and row `i`, the label
/// `k_(c') w^(i')` of the cell `(c', i') = sigma(c, i)`. Interpolated, these
/// are the polynomials `sigma_c`.
///
/// ```
/// use arrabbiata_field::{Field, TwoAdicField};
/// use arrabbiata_pasta::Fq as F;
/// use arrabbiata_permutation::{Permutation, labels, shifts};
/// use arrabbiata_poly::Domain;
/// let p = Permutation::identity(2, 2);
/// let domain = Domain::<F>::new(1).unwrap();
/// let k = shifts::<F>(2, 2).unwrap();
/// // The identity labels each cell by itself.
/// assert_eq!(labels(&p, &k, &domain)[1], vec![k[1], k[1] * domain.element(1)]);
/// ```
#[must_use]
pub fn labels<F>(permutation: &Permutation, shifts: &[F], domain: &Domain<F>) -> Vec<Vec<F>>
where
    F: TwoAdicField,
{
    let n = permutation.rows;
    (0..permutation.columns)
        .map(|c| {
            (0..n)
                .map(|i| {
                    let target = permutation.sigma[c * n + i];
                    shifts[target / n] * domain.element(target % n)
                })
                .collect()
        })
        .collect()
}

/// The grand product `z`: `z_0 = 1`, `z_(i+1) = z_i num_i / den_i` with
/// `num_i = prod_c (w_c(i) + beta k_c w^i + gamma)` and
/// `den_i = prod_c (w_c(i) + beta label_c(i) + gamma)`, for `i < n - 1`.
///
/// # Errors
///
/// [`Error::Shape`] if the columns, shifts and labels do not agree in
/// number and length; [`Error::Denominator`] if a denominator vanishes.
///
/// ```
/// use arrabbiata_field::{Field, TwoAdicField};
/// use arrabbiata_pasta::Fq as F;
/// use arrabbiata_permutation::{Permutation, grand_product, labels, shifts};
/// use arrabbiata_poly::Domain;
/// // With the identity, every factor is 1.
/// let p = Permutation::identity(1, 4);
/// let domain = Domain::<F>::new(2).unwrap();
/// let k = shifts::<F>(1, 4).unwrap();
/// let column = [vec![F::from_u64(9); 4]];
/// let z = grand_product(&column, &k, &labels(&p, &k, &domain), &domain, F::from_u64(2), F::from_u64(3)).unwrap();
/// assert_eq!(z, vec![F::ONE; 4]);
/// ```
pub fn grand_product<F, C>(
    columns: &[C],
    shifts: &[F],
    labels: &[Vec<F>],
    domain: &Domain<F>,
    beta: F,
    gamma: F,
) -> Result<Vec<F>, Error>
where
    F: TwoAdicField,
    C: AsRef<[F]>,
{
    let n = domain.size();
    let shaped = columns.len() == shifts.len()
        && columns.len() == labels.len()
        && columns.iter().all(|c| c.as_ref().len() == n)
        && labels.iter().all(|l| l.len() == n);
    if !shaped {
        return Err(Error::Shape);
    }
    let mut z = vec![F::ONE; n];
    for i in 0..n - 1 {
        let x = domain.element(i);
        let mut num = F::ONE;
        let mut den = F::ONE;
        for ((column, shift), label) in columns.iter().zip(shifts).zip(labels) {
            let w = column.as_ref()[i];
            num = num * (w + beta * *shift * x + gamma);
            den = den * (w + beta * label[i] + gamma);
        }
        z[i + 1] = z[i] * num * den.inverse().ok_or(Error::Denominator)?;
    }
    Ok(z)
}

/// Whether the grand product closes: the factor of the last row brings
/// `z_(n-1)` back to 1, which, over the cycle `H`, is the product identity
/// holding on every row. Respected columns close; others do not, except
/// with probability about `k n / |F|` over `beta, gamma`.
///
/// ```
/// use arrabbiata_field::{Field, TwoAdicField};
/// use arrabbiata_pasta::Fq as F;
/// use arrabbiata_permutation::{Permutation, closes, grand_product, labels, shifts};
/// use arrabbiata_poly::Domain;
/// let p = Permutation::new(1, 2, vec![1, 0]).unwrap();
/// let domain = Domain::<F>::new(1).unwrap();
/// let k = shifts::<F>(1, 2).unwrap();
/// let l = labels(&p, &k, &domain);
/// let (beta, gamma) = (F::from_u64(2), F::from_u64(3));
/// let column = [vec![F::ONE, F::ONE]];
/// let z = grand_product(&column, &k, &l, &domain, beta, gamma).unwrap();
/// assert!(closes(&column, &k, &l, &domain, &z, beta, gamma));
/// ```
#[must_use]
pub fn closes<F, C>(
    columns: &[C],
    shifts: &[F],
    labels: &[Vec<F>],
    domain: &Domain<F>,
    z: &[F],
    beta: F,
    gamma: F,
) -> bool
where
    F: TwoAdicField,
    C: AsRef<[F]>,
{
    let n = domain.size();
    let last = n - 1;
    let x = domain.element(last);
    let mut num = z[last];
    let mut den = F::ONE;
    for ((column, shift), label) in columns.iter().zip(shifts).zip(labels) {
        let w = column.as_ref()[last];
        num = num * (w + beta * *shift * x + gamma);
        den = den * (w + beta * label[last] + gamma);
    }
    num == den
}

/// The values the identities read at a point `x`: each permuted column and
/// its `sigma` polynomial at `x`, `z` at `x` and `w x`, and `L_0(x)`.
///
/// ```
/// use arrabbiata_field::Field;
/// use arrabbiata_pasta::Fq as F;
/// use arrabbiata_permutation::At;
/// let at = At { x: F::ONE, witness: &[F::ONE], sigmas: &[F::ONE], z: F::ONE, z_next: F::ONE, l0: F::ZERO };
/// assert_eq!(at.witness.len(), 1);
/// ```
#[derive(Clone, Copy, Debug)]
pub struct At<'a, F> {
    /// The point.
    pub x: F,
    /// The permuted columns at `x`.
    pub witness: &'a [F],
    /// The `sigma` polynomials at `x`.
    pub sigmas: &'a [F],
    /// The grand product at `x`.
    pub z: F,
    /// The grand product at `w x`.
    pub z_next: F,
    /// The first Lagrange polynomial at `x`.
    pub l0: F,
}

/// The two identity terms at a point, each vanishing on `H` for an honest
/// prover: the product step
/// `z prod_c (w_c + beta k_c x + gamma) - z(w x) prod_c (w_c + beta sigma_c + gamma)`
/// and the boundary `L_0 (z - 1)`. A protocol weights them by its own
/// separating challenge.
///
/// ```
/// use arrabbiata_field::Field;
/// use arrabbiata_pasta::Fq as F;
/// use arrabbiata_permutation::{At, terms};
/// // One column, the identity permutation at the point x = sigma = k x:
/// // the step is z - z(w x).
/// let at = At { x: F::ONE, witness: &[F::from_u64(4)], sigmas: &[F::ONE], z: F::from_u64(7), z_next: F::from_u64(7), l0: F::ONE };
/// let [step, boundary] = terms(&at, &[F::ONE], F::from_u64(2), F::from_u64(3));
/// assert!(step.is_zero());
/// assert_eq!(boundary, F::from_u64(6));
/// ```
#[must_use]
pub fn terms<F>(at: &At<'_, F>, shifts: &[F], beta: F, gamma: F) -> [F; 2]
where
    F: Field,
{
    let mut left = at.z;
    let mut right = at.z_next;
    for ((w, shift), sigma) in at.witness.iter().zip(shifts).zip(at.sigmas) {
        left = left * (*w + beta * *shift * at.x + gamma);
        right = right * (*w + beta * *sigma + gamma);
    }
    [left - right, at.l0 * (at.z - F::ONE)]
}

/// The degree of the product step in the column polynomials: the number of
/// permuted columns, plus one for `z`.
///
/// ```
/// use arrabbiata_permutation::degree;
/// assert_eq!(degree(7), 8);
/// ```
#[must_use]
pub const fn degree(columns: usize) -> usize {
    columns + 1
}
