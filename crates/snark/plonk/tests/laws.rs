proptest! {
    /// `iter` and `iter_mut` traverse the same shape in the same order, of
    /// length `2W + X + Q + 3` plus the rotated openings.
    #[test]
    fn opened_traversals_agree(values in prop::collection::vec(any::<u64>(), 20), rw in 0usize..4, rf in 0usize..4) {
        let mut v = values.iter().copied();
        let mut next = || v.next().unwrap();
        let mut o = Opened::<u64, 2, 1, 2> {
            witness: [next(), next()],
            fixed: [next()],
            selectors: [next(), next()],
            sigmas: [next(), next()],
            z: next(),
            t: next(),
            z_next: next(),
            witness_rotated: (0..rw).map(|_| next()).collect(),
            fixed_rotated: (0..rf).map(|_| next()).collect(),
        };
        let order: Vec<u64> = o.iter().copied().collect();
        prop_assert_eq!(order.len(), 2 * 2 + 1 + 2 + 3 + rw + rf);
        prop_assert_eq!(&order[..], &values[..order.len()]);
        for (i, x) in o.iter_mut().enumerate() {
            *x = i as u64;
        }
        prop_assert!(o.iter().copied().eq(0..order.len() as u64));
    }
}
